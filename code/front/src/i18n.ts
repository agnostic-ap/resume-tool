export function useI18n() {
  const store = useResumeStore()
  const locale = computed(() => store.config.locale)
  function t(key: keyof typeof messages['zh-CN']) {
    return messages[locale.value][key] ?? messages['zh-CN'][key]
  }
  return { locale, t }
}
